import { build } from 'esbuild';
import assert from 'node:assert/strict';
const result = await build({ entryPoints: ['src/mpc-preset-navigation.ts'], bundle: true, format: 'esm', write: false });
const { PresetNavigation } = await import(`data:text/javascript;base64,${Buffer.from(result.outputFiles[0].text).toString('base64')}`);
const sequential = new PresetNavigation(4);
sequential.select(0);
assert.equal(sequential.previous(), 0, 'empty history remains current');
assert.equal(sequential.next(), 1);
assert.equal(sequential.next(), 2, 'rapid requests advance pending intent');
assert.equal(sequential.index, 0, 'pending intent does not change displayed index');
sequential.cancel();
assert.equal(sequential.previous(), 0, 'failed requests never enter history');
sequential.select(0); sequential.select(1); sequential.select(2);
assert.equal(sequential.previous(), 1);
sequential.cancel();
assert.equal(sequential.previous(), 1, 'failed Previous does not consume history');
sequential.select(1);
assert.equal(sequential.previous(), 0);
sequential.select(0);
assert.equal(sequential.previous(), 0);
const shuffled = new PresetNavigation(5, () => .8);
shuffled.select(0); shuffled.shuffle = true;
assert.equal(shuffled.next(), 4); shuffled.select(4);
assert.equal(shuffled.next(), 3); shuffled.select(3);
assert.equal(shuffled.previous(), 4); shuffled.select(4);
assert.equal(shuffled.previous(), 0);
const single = new PresetNavigation(1); single.shuffle = true;
assert.equal(single.next(), 0); single.select(0); assert.equal(single.previous(), 0);
assert.throws(() => new PresetNavigation(0));
const filtered = new PresetNavigation(6, () => .99);
filtered.select(0);filtered.shuffle=true;
assert.equal(filtered.next([1,3,5]),5);
assert.equal(filtered.next([1,3,5]),3,'rapid shuffle excludes pending choice');
filtered.select(3);
assert.equal(filtered.next([3]),null,'singleton current cannot fall back to unrated presets');
assert.equal(filtered.next([]),null);
filtered.shuffle=false;
assert.equal(filtered.next([1,5]),5);
assert.equal(filtered.next([1,5]),1,'ordered navigation skips flagged entries');
console.log('Preset navigation: committed history, failed/cancelled requests, rapid intent, shuffle, singleton PASS');
