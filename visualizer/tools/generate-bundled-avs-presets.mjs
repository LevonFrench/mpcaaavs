import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { basename, resolve } from 'node:path';

const root = resolve(import.meta.dirname, '..');
const output = resolve(root, 'src/avs/bundled-presets.generated.ts');
const check = process.argv.includes('--check');
const collections = [
  { id: 'community-picks', label: 'Community Picks', directory: 'assets/avs-presets/community-picks', expected: 50 },
  { id: 'winamp-5-picks', label: 'Winamp 5 Picks', directory: 'assets/avs-presets/winamp-5-picks', expected: 74 },
];

const entries = collections.flatMap((collection) => {
  const files = readdirSync(resolve(root, collection.directory), { withFileTypes: true })
    .filter((entry) => entry.isFile() && entry.name.toLowerCase().endsWith('.avs'))
    .map((entry) => ({ ...collection, fileName: entry.name }))
    .sort((a, b) => a.fileName.localeCompare(b.fileName, 'en', { sensitivity: 'base', numeric: true }));
  if (files.length !== collection.expected) {
    throw new Error(`${collection.label}: expected ${collection.expected} presets, found ${files.length}`);
  }
  for (const entry of files) {
    const header = readFileSync(resolve(root, entry.directory, entry.fileName)).subarray(0, 24).toString('latin1');
    if (!header.startsWith('Nullsoft AVS Preset 0.')) throw new Error(`${entry.fileName}: invalid AVS preset header`);
  }
  return files;
});

const ids = entries.map((entry) => `${entry.id}/${basename(entry.fileName, '.avs')}`);
if (new Set(ids).size !== ids.length) throw new Error('bundled AVS preset IDs are not unique');

const imports = entries.map((entry, index) => {
  const specifier = `../../${entry.directory}/${entry.fileName.replaceAll('\\', '/')}`;
  return `import preset${String(index).padStart(3, '0')} from ${JSON.stringify(specifier)};`;
});
const rows = entries.map((entry, index) => {
  const name = basename(entry.fileName, '.avs');
  return `  { id: ${JSON.stringify(`${entry.id}/${name}`)}, name: ${JSON.stringify(name)}, fileName: ${JSON.stringify(entry.fileName)}, collection: ${JSON.stringify(entry.label)}, url: preset${String(index).padStart(3, '0')} },`;
});

const source = [
  '// Generated by tools/generate-bundled-avs-presets.mjs. Do not hand-edit.',
  ...imports,
  '',
  'export const BUNDLED_AVS_PRESET_CATALOG = [',
  ...rows,
  '] as const;',
  '',
].join('\n');

if (check) {
  const current = readFileSync(output, 'utf8');
  if (current !== source) {
    console.error('bundled AVS preset catalog is stale; run npm run avs:catalog');
    process.exit(1);
  }
  console.log(`bundled-avs-presets: PASS (${entries.length} presets)`);
} else {
  writeFileSync(output, source);
  console.log(`bundled-avs-presets: wrote ${entries.length} presets`);
}
